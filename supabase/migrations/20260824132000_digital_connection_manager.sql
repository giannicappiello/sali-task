create policy "digital connection audit read" on public.crm_connection_audit
  for select to authenticated using(public.crm_can_view_connection_manager());

create or replace function public.crm_claim_sync_run_service(
  target_connection_id uuid,
  target_sync_type text,
  target_mode text,
  target_idempotency_key text,
  target_triggered_by uuid default null
) returns uuid language plpgsql security definer set search_path=public as $$
declare run_id uuid; connection_enabled boolean;
begin
  if auth.role() <> 'service_role' then
    raise exception 'Operazione riservata al servizio Digital.' using errcode='42501';
  end if;
  select abilitata into connection_enabled
  from public.crm_external_connections where id=target_connection_id for update;
  if connection_enabled is null then raise exception 'Connessione non trovata.'; end if;
  if not connection_enabled then raise exception 'Connessione o sincronizzazione disattivata.'; end if;
  insert into public.crm_sync_runs(
    connection_id,sync_type,mode,status,idempotency_key,started_at,heartbeat_at,triggered_by
  ) values(
    target_connection_id,target_sync_type,coalesce(target_mode,'incremental'),
    'running',target_idempotency_key,now(),now(),target_triggered_by
  ) returning id into run_id;
  update public.crm_external_connections
    set stato='sincronizzazione_in_corso',aggiornata_il=now()
    where id=target_connection_id;
  return run_id;
exception when unique_violation then
  raise exception 'Sincronizzazione dello stesso tipo gia in corso.' using errcode='55P03';
end $$;
revoke all on function public.crm_claim_sync_run_service(uuid,text,text,text,uuid) from public,anon,authenticated;
grant execute on function public.crm_claim_sync_run_service(uuid,text,text,text,uuid) to service_role;

create or replace function public.crm_complete_sync_run_service(
  target_run_id uuid,
  target_status text,
  target_counts jsonb default '{}',
  target_error_code text default null,
  target_error_message text default null,
  target_details jsonb default '{}'
) returns void language plpgsql security definer set search_path=public as $$
declare target_connection uuid;
begin
  if auth.role() <> 'service_role' then
    raise exception 'Operazione riservata al servizio Digital.' using errcode='42501';
  end if;
  if target_status not in ('completed','partial','failed','cancelled') then
    raise exception 'Stato finale non valido.';
  end if;
  update public.crm_sync_runs set
    status=target_status,
    completed_at=now(),
    heartbeat_at=now(),
    duration_ms=greatest(0,extract(epoch from (now()-started_at))*1000)::bigint,
    records_read=coalesce((target_counts->>'read')::integer,records_read),
    records_inserted=coalesce((target_counts->>'inserted')::integer,records_inserted),
    records_updated=coalesce((target_counts->>'updated')::integer,records_updated),
    records_failed=coalesce((target_counts->>'failed')::integer,records_failed),
    error_code=target_error_code,
    error_message=left(target_error_message,500),
    details=coalesce(target_details,'{}')
  where id=target_run_id returning connection_id into target_connection;
  update public.crm_external_connections set
    stato=case when target_status='failed' then 'errore' else 'connesso' end,
    ultimo_sync_il=case when target_status in ('completed','partial') then now() else ultimo_sync_il end,
    ultimo_errore=case when target_status='failed' then left(target_error_message,500) else null end,
    prossima_run_il=case when sync_attivo and sync_frequency='daily' then now()+interval '1 day' else null end,
    aggiornata_il=now()
  where id=target_connection;
end $$;
revoke all on function public.crm_complete_sync_run_service(uuid,text,jsonb,text,text,jsonb) from public,anon,authenticated;
grant execute on function public.crm_complete_sync_run_service(uuid,text,jsonb,text,text,jsonb) to service_role;

