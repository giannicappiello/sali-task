-- WorkspaceMES V3. Schema additivo, disabilitato per default e senza backfill storico.
-- V1/V2 restano invariati; tutte le mutazioni V3 passano da RPC service-role fail-closed.

create table if not exists public.workspace_finished_bom_revisions (
  id bigint generated by default as identity primary key,
  external_id uuid not null unique default gen_random_uuid(),
  finished_article_code text not null,
  revision integer not null check (revision > 0),
  source text not null default 'MEXAL',
  source_hash text not null,
  base_quantity numeric(18,6) not null default 1 check (base_quantity > 0),
  unit_of_measure text not null,
  effective_from timestamptz not null,
  effective_to timestamptz,
  is_current boolean not null default true,
  source_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (finished_article_code, revision),
  check (effective_to is null or effective_to >= effective_from)
);

create unique index if not exists workspace_finished_bom_current_uniq
  on public.workspace_finished_bom_revisions (finished_article_code) where is_current;

create table if not exists public.workspace_finished_bom_lines (
  id bigint generated by default as identity primary key,
  external_id uuid not null unique default gen_random_uuid(),
  revision_id bigint not null references public.workspace_finished_bom_revisions(id) on delete restrict,
  line_number integer not null check (line_number > 0),
  article_code text not null,
  description text,
  quantity numeric(18,6) not null check (quantity > 0),
  unit_of_measure text not null,
  component_kind text not null check (component_kind in ('DIRECT_COMPONENT','FORMULA_COMPONENT')),
  classification_source text not null,
  formula_external_ref text,
  metadata jsonb not null default '{}'::jsonb,
  unique (revision_id, line_number)
);

