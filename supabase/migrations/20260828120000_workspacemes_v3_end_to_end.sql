create or replace function public.create_workspace_v3_purchase_document(
  p_external_id uuid,
  p_document_type text,
  p_parent_document_id bigint,
  p_supplier_external_ref text,
  p_document_number text,
  p_currency text,
  p_valid_until date,
  p_payload_hash text,
  p_idempotency_key text,
  p_correlation_id uuid,
  p_actor text,
  p_lines jsonb
) returns table(document_id bigint,document_type text,status text,created boolean)
language plpgsql security definer set search_path=public as $$
declare
  v_document public.workspace_v3_purchase_documents%rowtype;
  v_parent public.workspace_v3_purchase_documents%rowtype;
  v_line jsonb;
  v_requirement public.workspace_v3_purchase_requirements%rowtype;
  v_expected_parent text;
  v_requirement_status text;
begin
  if not coalesce((select enabled from public.workspace_v3_feature_flags where key='workspacemes.v3.purchasing'),false)
  then raise exception 'WORKSPACEMES_V3_PURCHASING_DISABLED'; end if;
  if p_document_type not in ('PROPOSAL','RFQ','QUOTE','SUPPLIER_ORDER') or jsonb_typeof(p_lines)<>'array' or jsonb_array_length(p_lines)=0
  then raise exception 'INVALID_V3_PURCHASE_DOCUMENT'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_idempotency_key,0));
  select * into v_document from public.workspace_v3_purchase_documents where idempotency_key=p_idempotency_key;
  if found then
    if v_document.payload_hash<>p_payload_hash then raise exception 'V3_PURCHASE_IDEMPOTENCY_CONFLICT'; end if;
    return query select v_document.id,v_document.document_type,v_document.status,false; return;
  end if;

  v_expected_parent := case p_document_type when 'RFQ' then 'PROPOSAL' when 'QUOTE' then 'RFQ' when 'SUPPLIER_ORDER' then 'QUOTE' else null end;
  if v_expected_parent is null and p_parent_document_id is not null then raise exception 'V3_PURCHASE_PARENT_NOT_ALLOWED'; end if;
  if v_expected_parent is not null then
    select * into v_parent from public.workspace_v3_purchase_documents where id=p_parent_document_id for update;
    if not found or v_parent.document_type<>v_expected_parent then raise exception 'V3_PURCHASE_PARENT_INVALID'; end if;
  end if;
  if p_document_type in ('QUOTE','SUPPLIER_ORDER') and nullif(trim(p_supplier_external_ref),'') is null
  then raise exception 'V3_PURCHASE_SUPPLIER_REQUIRED'; end if;

  insert into public.workspace_v3_purchase_documents(external_id,document_type,parent_document_id,supplier_external_ref,
    status,document_number,currency,valid_until,payload_hash,idempotency_key,correlation_id)
  values(p_external_id,p_document_type,p_parent_document_id,nullif(trim(p_supplier_external_ref),''),'PREPARED',
    nullif(trim(p_document_number),''),nullif(trim(p_currency),''),p_valid_until,p_payload_hash,p_idempotency_key,p_correlation_id)
  returning * into v_document;

  v_requirement_status := case p_document_type when 'PROPOSAL' then 'IN_PROPOSAL' when 'RFQ' then 'IN_RFQ'
    when 'QUOTE' then 'QUOTED' when 'SUPPLIER_ORDER' then 'ORDERED' end;
  for v_line in select value from jsonb_array_elements(p_lines) loop
    select * into v_requirement from public.workspace_v3_purchase_requirements
      where id=(v_line->>'requirementId')::bigint for update;
    if not found or v_requirement.status='CANCELLED' or (v_line->>'quantity')::numeric<=0 or
       (v_line->>'quantity')::numeric>v_requirement.required_quantity
    then raise exception 'V3_PURCHASE_REQUIREMENT_INVALID'; end if;
    if v_parent.id is not null and not exists(select 1 from public.workspace_v3_purchase_document_lines
      where document_id=v_parent.id and requirement_id=v_requirement.id)
    then raise exception 'V3_PURCHASE_LINEAGE_INVALID'; end if;
    insert into public.workspace_v3_purchase_document_lines(document_id,requirement_id,quantity,unit_price,expected_at)
    values(v_document.id,v_requirement.id,(v_line->>'quantity')::numeric,(v_line->>'unitPrice')::numeric,
      (v_line->>'expectedAt')::timestamptz);
    update public.workspace_v3_purchase_requirements set status=v_requirement_status,row_version=row_version+1,updated_at=now()
      where id=v_requirement.id;
  end loop;
  insert into public.workspace_v3_outbox(aggregate_type,aggregate_id,destination,event_type,sequence,payload,payload_hash,correlation_id)
  values('V3_PURCHASE_DOCUMENT',v_document.id::text,'WORKSPACE',
    case when p_document_type='SUPPLIER_ORDER' then 'SupplierOrderPreparedNotSent' else 'PurchaseDocumentPrepared' end,
    1,jsonb_build_object('documentId',v_document.id,'documentType',p_document_type,'sendToMexal',false),p_payload_hash,p_correlation_id);
  insert into public.workspace_v3_audit(aggregate_type,aggregate_id,action,actor_id,after_hash,payload,correlation_id)
  values('V3_PURCHASE_DOCUMENT',v_document.id::text,p_document_type||'_PREPARED',p_actor,p_payload_hash,
    jsonb_build_object('parentDocumentId',p_parent_document_id,'sendToMexal',false),p_correlation_id);
  return query select v_document.id,v_document.document_type,v_document.status,true;
end $$;

