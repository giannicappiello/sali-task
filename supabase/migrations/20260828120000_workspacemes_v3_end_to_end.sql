create table if not exists public.workspace_finished_bom_revisions (
  id bigint generated by default as identity primary key,
  external_id uuid not null unique default gen_random_uuid(),
  finished_article_code text not null,
  revision integer not null check (revision > 0),
  source text not null default 'MEXAL',
  source_hash text not null,
  base_quantity numeric(18,6) not null default 1 check (base_quantity > 0),
  unit_of_measure text not null,
  effective_from timestamptz not null,
