create or replace function public.confirm_workspace_v3_after_mes(
  p_preview_id bigint,
  p_external_id uuid,
  p_idempotency_key text,
  p_payload_hash text,
  p_expected_row_version bigint,
  p_mes_confirmation_id uuid,
  p_mes_production_order_id integer,
  p_mes_production_order_number text,
  p_actor text,
  p_correlation_id uuid,
  p_causation_id uuid default null
) returns table(saga_id bigint, status text, requirements_created integer)
language plpgsql security definer set search_path = public as $$
declare
  v_preview public.workspace_v3_previews%rowtype;
  v_saga public.workspace_v3_confirmation_sagas%rowtype;
  v_component public.workspace_v3_preview_components%rowtype;
  v_commitment_id bigint;
  v_requirements integer := 0;
begin
  if not coalesce((select enabled from public.workspace_v3_feature_flags where key='workspacemes.v3.confirm'), false) then
    raise exception 'WORKSPACEMES_V3_CONFIRM_DISABLED';
  end if;
  select * into v_preview from public.workspace_v3_previews where id=p_preview_id for update;
  if not found then raise exception 'V3_PREVIEW_NOT_FOUND'; end if;
  if v_preview.row_version <> p_expected_row_version then raise exception 'V3_CONCURRENT_MODIFICATION'; end if;
  if v_preview.status <> 'READY' then raise exception 'V3_PREVIEW_NOT_READY'; end if;
  select * into v_saga from public.workspace_v3_confirmation_sagas where idempotency_key=p_idempotency_key for update;
  if found then
    if v_saga.payload_hash <> p_payload_hash then raise exception 'V3_IDEMPOTENCY_CONFLICT'; end if;
    return query select v_saga.id, v_saga.status, 0;
    return;
  end if;
  insert into public.workspace_v3_confirmation_sagas(external_id,preview_id,idempotency_key,payload_hash,status,
    mes_confirmation_id,mes_production_order_id,mes_production_order_number,correlation_id,causation_id)
  values(p_external_id,p_preview_id,p_idempotency_key,p_payload_hash,'MATERIALIZING_WORKSPACE',
    p_mes_confirmation_id,p_mes_production_order_id,p_mes_production_order_number,p_correlation_id,p_causation_id)
  returning * into v_saga;
  for v_component in select * from public.workspace_v3_preview_components where preview_id=p_preview_id loop
    if v_component.required_quantity <= 0 then continue; end if;
    insert into public.workspace_v3_material_commitments(saga_id,preview_component_id,owner,article_code,unit_of_measure,quantity,source_commitment_id,status)
    values(v_saga.id,v_component.id,case when v_component.component_kind='DIRECT_COMPONENT' then 'WORKSPACE_DIRECT' else 'PROGREMES_MP_CERTIFIED' end,
      v_component.article_code,v_component.unit_of_measure,v_component.required_quantity,
      case when v_component.component_kind='FORMULA_MATERIAL' then p_mes_confirmation_id::text else null end,'ACTIVE')
    returning id into v_commitment_id;
    if v_component.uncovered_quantity > 0 then
      insert into public.workspace_v3_purchase_requirements(saga_id,commitment_id,article_code,unit_of_measure,required_quantity,expected_at,status,lineage)
      values(v_saga.id,v_commitment_id,v_component.article_code,v_component.unit_of_measure,v_component.uncovered_quantity,
        v_component.expected_available_at,'OPEN',jsonb_build_object('previewId',p_preview_id,'componentId',v_component.id,
        'productionOrderId',p_mes_production_order_id,'productionOrderNumber',p_mes_production_order_number));
      v_requirements := v_requirements + 1;
    end if;
  end loop;
  update public.workspace_v3_confirmation_sagas set status='COMPLETED',completed_at=now(),updated_at=now(),row_version=row_version+1 where id=v_saga.id;
  update public.workspace_v3_previews set status='CONFIRMED',confirmed_at=now(),row_version=row_version+1 where id=p_preview_id;
  insert into public.workspace_v3_outbox(aggregate_type,aggregate_id,destination,event_type,sequence,payload,payload_hash,correlation_id,causation_id)
  values('V3_CONFIRMATION_SAGA',v_saga.id::text,'WORKSPACE','WorkspaceV3Confirmed',1,
    jsonb_build_object('sagaId',v_saga.id,'previewId',p_preview_id,'productionOrderId',p_mes_production_order_id,'requirementsCreated',v_requirements),
    p_payload_hash,p_correlation_id,p_causation_id);
  insert into public.workspace_v3_audit(aggregate_type,aggregate_id,action,actor_id,after_hash,payload,correlation_id,causation_id)
  values('V3_CONFIRMATION_SAGA',v_saga.id::text,'CONFIRMED',p_actor,p_payload_hash,
    jsonb_build_object('previewId',p_preview_id,'requirementsCreated',v_requirements),p_correlation_id,p_causation_id);
  return query select v_saga.id, 'COMPLETED'::text, v_requirements;
end $$;

revoke all on function public.confirm_workspace_v3_after_mes(bigint,uuid,text,text,bigint,uuid,integer,text,text,uuid,uuid) from public,anon,authenticated;
grant execute on function public.confirm_workspace_v3_after_mes(bigint,uuid,text,text,bigint,uuid,integer,text,text,uuid,uuid) to service_role;

