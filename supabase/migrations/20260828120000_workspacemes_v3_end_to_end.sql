create or replace function public.apply_workspace_finished_bom_snapshot(
  p_finished_article_code text,
  p_source_hash text,
  p_unit_of_measure text,
  p_base_quantity numeric,
  p_source_payload jsonb,
  p_lines jsonb,
  p_captured_at timestamptz
) returns table(revision_id bigint, revision integer, changed boolean)
language plpgsql security definer set search_path=public as $$
declare
  v_previous public.workspace_finished_bom_revisions%rowtype;
  v_revision public.workspace_finished_bom_revisions%rowtype;
  v_line jsonb;
  v_number integer := 0;
begin
  if nullif(trim(p_finished_article_code),'') is null or nullif(trim(p_source_hash),'') is null or
     nullif(trim(p_unit_of_measure),'') is null or p_base_quantity <= 0 or jsonb_typeof(p_lines) <> 'array'
  then raise exception 'INVALID_FINISHED_BOM_SNAPSHOT'; end if;

  perform pg_advisory_xact_lock(hashtextextended(upper(trim(p_finished_article_code)),0));
  select * into v_previous from public.workspace_finished_bom_revisions
   where finished_article_code=upper(trim(p_finished_article_code)) and is_current for update;
  if found and v_previous.source_hash=p_source_hash then
    return query select v_previous.id,v_previous.revision,false;
    return;
  end if;

  if found then
    update public.workspace_finished_bom_revisions
       set is_current=false,effective_to=p_captured_at
     where id=v_previous.id;
  end if;

  insert into public.workspace_finished_bom_revisions(
    finished_article_code,revision,source,source_hash,base_quantity,unit_of_measure,
    effective_from,is_current,source_payload)
  values(upper(trim(p_finished_article_code)),coalesce(v_previous.revision,0)+1,'MEXAL',p_source_hash,
    p_base_quantity,upper(trim(p_unit_of_measure)),p_captured_at,true,coalesce(p_source_payload,'{}'::jsonb))
  returning * into v_revision;

  for v_line in select value from jsonb_array_elements(p_lines) loop
    v_number := v_number+1;
    insert into public.workspace_finished_bom_lines(
      revision_id,line_number,source_line_key,article_code,description,quantity,unit_of_measure,
      component_kind,classification_source,formula_external_ref,source_unit_type,is_removed,metadata)
    values(v_revision.id,v_number,v_line->>'sourceLineKey',upper(v_line->>'articleCode'),v_line->>'description',
      (v_line->>'quantity')::numeric,upper(v_line->>'unitOfMeasure'),v_line->>'componentKind',
      v_line->>'classificationSource',nullif(v_line->>'formulaExternalRef',''),nullif(v_line->>'sourceUnitType',''),
      false,coalesce(v_line->'metadata','{}'::jsonb));
  end loop;

  if v_previous.id is not null then
    insert into public.workspace_finished_bom_lines(
      revision_id,line_number,source_line_key,article_code,description,quantity,unit_of_measure,
      component_kind,classification_source,formula_external_ref,source_unit_type,is_removed,removed_at,metadata)
    select v_revision.id,v_number+row_number() over(order by old_line.line_number),old_line.source_line_key,
      old_line.article_code,old_line.description,old_line.quantity,old_line.unit_of_measure,old_line.component_kind,
      old_line.classification_source,old_line.formula_external_ref,old_line.source_unit_type,true,p_captured_at,
      old_line.metadata||jsonb_build_object('removedFromRevision',v_previous.revision)
    from public.workspace_finished_bom_lines old_line
    where old_line.revision_id=v_previous.id and not old_line.is_removed
      and not exists(select 1 from jsonb_array_elements(p_lines) fresh where fresh->>'sourceLineKey'=old_line.source_line_key);
  end if;

  return query select v_revision.id,v_revision.revision,true;
end $$;

create or replace function public.apply_workspace_supplier_order_snapshot(
  p_snapshot_hash text,
  p_source_payload jsonb,
  p_lines jsonb,
  p_captured_at timestamptz
) returns table(snapshot_id bigint, changed boolean)
language plpgsql security definer set search_path=public as $$
declare v_snapshot_id bigint;
begin
  if nullif(trim(p_snapshot_hash),'') is null or jsonb_typeof(p_lines)<>'array'
  then raise exception 'INVALID_SUPPLIER_ORDER_SNAPSHOT'; end if;
  select id into v_snapshot_id from public.workspace_supplier_order_snapshots where snapshot_hash=p_snapshot_hash;
  if found then return query select v_snapshot_id,false; return; end if;

  insert into public.workspace_supplier_order_snapshots(snapshot_hash,captured_at,orders_count,lines_count,source_payload)
  values(p_snapshot_hash,p_captured_at,(select count(distinct value->>'orderExternalKey') from jsonb_array_elements(p_lines)),
    jsonb_array_length(p_lines),coalesce(p_source_payload,'{}'::jsonb)) returning id into v_snapshot_id;

  insert into public.workspace_supplier_order_snapshot_lines(
    snapshot_id,order_external_key,line_external_key,supplier_code,supplier_name,article_code,description,
    unit_of_measure,ordered_quantity,received_quantity,remaining_quantity,expected_at,order_date,
    order_status,active,receipt_semantics,source_payload)
  select v_snapshot_id,x.order_external_key,x.line_external_key,x.supplier_code,x.supplier_name,x.article_code,
    x.description,x.unit_of_measure,x.ordered_quantity,0,x.ordered_quantity,x.expected_at,x.order_date,
    'OPEN',true,'NOT_EXPOSED_BY_MEXAL_ENDPOINT',x.source_payload
  from jsonb_to_recordset(p_lines) as x(order_external_key text,line_external_key text,supplier_code text,
    supplier_name text,article_code text,description text,unit_of_measure text,ordered_quantity numeric,
    expected_at timestamptz,order_date date,source_payload jsonb);
  return query select v_snapshot_id,true;
end $$;

create or replace function public.persist_workspace_v3_preview(
  p_external_id uuid,
  p_production_request_id uuid,
  p_preview_hash text,
  p_idempotency_key text,
  p_payload_hash text,
  p_status text,
  p_oct_revision integer,
  p_oct_hash text,
  p_bom_hash text,
  p_availability_version text,
  p_snapshot jsonb,
  p_correlation_id uuid,
  p_causation_id uuid,
  p_requested_by uuid,
  p_sources jsonb,
  p_components jsonb
) returns table(preview_id bigint,status text,row_version bigint,created boolean)
language plpgsql security definer set search_path=public as $$
declare
  v_preview public.workspace_v3_previews%rowtype;
  v_item jsonb;
  v_parent_id bigint;
begin
  select * into v_preview from public.workspace_v3_previews where idempotency_key=p_idempotency_key;
  if found then
    if v_preview.payload_hash<>p_payload_hash then raise exception 'V3_PREVIEW_IDEMPOTENCY_CONFLICT'; end if;
    return query select v_preview.id,v_preview.status,v_preview.row_version,false;
    return;
  end if;
  if p_status not in ('READY','BLOCKED') or jsonb_typeof(p_sources)<>'array' or jsonb_typeof(p_components)<>'array'
  then raise exception 'INVALID_V3_PREVIEW'; end if;

  insert into public.workspace_v3_previews(external_id,production_request_id,preview_hash,idempotency_key,payload_hash,
    status,oct_revision,oct_hash,bom_hash,availability_version,snapshot,correlation_id,causation_id,requested_by)
  values(p_external_id,p_production_request_id,p_preview_hash,p_idempotency_key,p_payload_hash,p_status,p_oct_revision,
    p_oct_hash,p_bom_hash,p_availability_version,p_snapshot,p_correlation_id,p_causation_id,p_requested_by)
  returning * into v_preview;

  insert into public.workspace_v3_preview_sources(preview_id,order_id,order_line_id,bom_revision_id,
    finished_article_code,finished_quantity,unit_of_measure,oct_revision,oct_hash,bom_hash)
  select v_preview.id,x.order_id,x.order_line_id,x.bom_revision_id,x.finished_article_code,x.finished_quantity,
    x.unit_of_measure,x.oct_revision,x.oct_hash,x.bom_hash
  from jsonb_to_recordset(p_sources) as x(order_id uuid,order_line_id uuid,bom_revision_id bigint,
    finished_article_code text,finished_quantity numeric,unit_of_measure text,oct_revision integer,oct_hash text,bom_hash text);

  for v_item in select value from jsonb_array_elements(p_components)
    where value->>'componentKind'<>'FORMULA_MATERIAL'
  loop
    insert into public.workspace_v3_preview_components(preview_id,bom_line_id,component_kind,article_code,
      unit_of_measure,required_quantity,on_hand_quantity,committed_quantity,incoming_quantity,uncovered_quantity,
      required_at,expected_available_at,calculation_owner,formula_code,formula_revision,formula_snapshot_hash,batch,station,
      filling,blocker_code,certified_payload)
    values(v_preview.id,(v_item->>'bomLineId')::bigint,v_item->>'componentKind',upper(v_item->>'articleCode'),
      upper(v_item->>'unitOfMeasure'),(v_item->>'requiredQuantity')::numeric,coalesce((v_item->>'onHandQuantity')::numeric,0),
      coalesce((v_item->>'committedQuantity')::numeric,0),coalesce((v_item->>'incomingQuantity')::numeric,0),
      coalesce((v_item->>'uncoveredQuantity')::numeric,0),(v_item->>'requiredAt')::timestamptz,(v_item->>'expectedAvailableAt')::timestamptz,
      v_item->>'calculationOwner',nullif(v_item->>'formulaCode',''),nullif((v_item->>'formulaRevision')::integer,0),
      nullif(v_item->>'formulaSnapshotHash',''),nullif(v_item->>'batch',''),nullif(v_item->>'station',''),
      nullif(v_item->>'filling',''),nullif(v_item->>'blockerCode',''),coalesce(v_item->'certifiedPayload','{}'::jsonb));
  end loop;

  for v_item in select value from jsonb_array_elements(p_components)
    where value->>'componentKind'='FORMULA_MATERIAL'
  loop
    select id into v_parent_id from public.workspace_v3_preview_components
      where preview_id=v_preview.id and component_kind='FORMULA_COMPONENT'
        and bom_line_id=(v_item->>'bomLineId')::bigint and article_code=upper(v_item->>'parentArticleCode');
    if v_parent_id is null then raise exception 'V3_FORMULA_PARENT_NOT_FOUND'; end if;
    insert into public.workspace_v3_preview_components(preview_id,bom_line_id,component_kind,parent_component_id,
      article_code,unit_of_measure,required_quantity,on_hand_quantity,committed_quantity,incoming_quantity,
      uncovered_quantity,required_at,expected_available_at,calculation_owner,formula_code,formula_revision,
      formula_snapshot_hash,batch,station,filling,blocker_code,certified_payload)
    values(v_preview.id,(v_item->>'bomLineId')::bigint,'FORMULA_MATERIAL',v_parent_id,upper(v_item->>'articleCode'),
      upper(v_item->>'unitOfMeasure'),(v_item->>'requiredQuantity')::numeric,coalesce((v_item->>'onHandQuantity')::numeric,0),
      coalesce((v_item->>'committedQuantity')::numeric,0),coalesce((v_item->>'incomingQuantity')::numeric,0),
      coalesce((v_item->>'uncoveredQuantity')::numeric,0),(v_item->>'requiredAt')::timestamptz,(v_item->>'expectedAvailableAt')::timestamptz,'PROGREMES',
      nullif(v_item->>'formulaCode',''),nullif((v_item->>'formulaRevision')::integer,0),
      nullif(v_item->>'formulaSnapshotHash',''),nullif(v_item->>'batch',''),nullif(v_item->>'station',''),
      nullif(v_item->>'filling',''),nullif(v_item->>'blockerCode',''),coalesce(v_item->'certifiedPayload','{}'::jsonb));
  end loop;

  insert into public.workspace_v3_audit(aggregate_type,aggregate_id,action,actor_id,after_hash,payload,correlation_id,causation_id)
  values('V3_PREVIEW',v_preview.id::text,'PREVIEW_CAPTURED',coalesce(p_requested_by::text,'system'),p_preview_hash,p_snapshot,p_correlation_id,p_causation_id);
  return query select v_preview.id,v_preview.status,v_preview.row_version,true;
end $$;

