create table if not exists public.workspace_production_availability_snapshots (
  id bigint generated by default as identity primary key,
  production_request_id uuid not null references public.workspace_production_requests(id) on delete cascade,
  ordine_id uuid not null references public.ordini_testate(id) on delete cascade,
  ordine_riga_id uuid not null references public.ordini_righe(id) on delete cascade,
  codice_articolo text not null,
  quantita_richiesta_oct numeric(18,6) not null check (quantita_richiesta_oct >= 0),
  quantita_richiesta_prodotto numeric(18,6) not null check (quantita_richiesta_prodotto >= 0),
  quantita_disponibile_pf numeric(18,6) not null check (quantita_disponibile_pf >= 0),
  quantita_coperta_scorta numeric(18,6) not null check (quantita_coperta_scorta >= 0),
  quantita_da_produrre numeric(18,6) not null check (quantita_da_produrre >= 0),
  unita_misura_oct text,
  unita_misura_prodotto text not null,
  unita_misura_effettiva text not null,
  conversione jsonb,
  regola_magazzini jsonb not null,
  product_updated_at timestamptz not null,
  product_last_sync_at timestamptz,
  snapshot_hash text not null,
  snapshot jsonb not null,
  captured_at timestamptz not null default now(),
  last_validated_at timestamptz not null default now(),
  unique (production_request_id, snapshot_hash)
);

