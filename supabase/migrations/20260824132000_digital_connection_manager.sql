create or replace function public.crm_can_view_connection_manager()
returns boolean language sql stable security definer set search_path=public as $$
  with me as (
    select u.id,coalesce(r.amministratore_workspace,false) admin,
      coalesce(r.livello_accesso,'lettura') role_level
    from public.utenti u left join public.ruoli r on r.id=u.ruolo_id
    where u.auth_user_id=auth.uid() and u.attivo is not false limit 1
  )
  select coalesce((select admin or role_level='amministrazione' or exists(
    select 1 from public.permessi_utente pu
    join public.permessi p on p.id=pu.permesso_id
    where pu.utente_id=me.id and p.codice='integrations.configure'
  ) from me),false)
$$;
revoke all on function public.crm_can_view_connection_manager() from public,anon;
grant execute on function public.crm_can_view_connection_manager() to authenticated,service_role;

