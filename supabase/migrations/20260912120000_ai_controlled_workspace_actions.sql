  name text not null,
  dataset text not null check(dataset in ('orders','rdp','op','lots','documents','materials','synchronizations')),
  condition jsonb not null,
  frequency_minutes integer not null check(frequency_minutes between 5 and 10080),
  notification_mode text not null default 'on_change' check(notification_mode in ('on_change','on_match','daily_summary')),
  active boolean not null default true,
  last_evaluated_at timestamptz,
  last_result jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

